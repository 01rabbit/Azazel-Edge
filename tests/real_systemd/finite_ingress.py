class SystemdCallError(OSError):
    pass


class _BusError(ctypes.Structure):
    _fields_ = [
        ("name", ctypes.c_char_p),
        ("message", ctypes.c_char_p),
        ("need_free", ctypes.c_int),
    ]


class SystemdUnitClient:
    """Existing system bus, one connection and fixed owned unit only."""

    def __init__(self):
        self.bus = ctypes.c_void_p()
        self.trace = []
        self.lib = ctypes.CDLL("libsystemd.so.0")
        self.lib.sd_bus_open_system.argtypes = [ctypes.POINTER(ctypes.c_void_p)]
        self.lib.sd_bus_open_system.restype = ctypes.c_int
        self.lib.sd_bus_set_method_call_timeout.argtypes = [
            ctypes.c_void_p,
            ctypes.c_uint64,
        ]
        self.lib.sd_bus_set_method_call_timeout.restype = ctypes.c_int
        self.lib.sd_bus_call_method.argtypes = [
            ctypes.c_void_p,
            ctypes.c_char_p,
            ctypes.c_char_p,
            ctypes.c_char_p,
            ctypes.c_char_p,
            ctypes.POINTER(_BusError),
            ctypes.POINTER(ctypes.c_void_p),
            ctypes.c_char_p,
        ]
        self.lib.sd_bus_call_method.restype = ctypes.c_int
        self.lib.sd_bus_message_unref.argtypes = [ctypes.c_void_p]
        self.lib.sd_bus_message_unref.restype = ctypes.c_void_p
        self.lib.sd_bus_error_free.argtypes = [ctypes.POINTER(_BusError)]
        self.lib.sd_bus_error_free.restype = ctypes.c_void_p
        self.lib.sd_bus_flush.argtypes = [ctypes.c_void_p]
        self.lib.sd_bus_flush.restype = ctypes.c_int
        self.lib.sd_bus_close.argtypes = [ctypes.c_void_p]
        self.lib.sd_bus_close.restype = None
        self.lib.sd_bus_unref.argtypes = [ctypes.c_void_p]
        self.lib.sd_bus_unref.restype = ctypes.c_void_p

    def open(self):
        self.checked(
            "open_system_bus", self.lib.sd_bus_open_system(ctypes.byref(self.bus))
        )
        self.checked(
            "set_call_timeout",
            self.lib.sd_bus_set_method_call_timeout(self.bus, CALL_TIMEOUT_USEC),
        )

    def checked(self, method, result, name=None, message=None):
        self.trace.append(
            dict(method=method, returncode=result, error_name=name, message=message)
        )
        if result < 0:
            raise SystemdCallError(
                f"{method}: {name or 'errno'}:{message or os.strerror(-result)}"
            )

    def call(self, method, unit):
        assert (
            method in ("RefUnit", "ResetFailedUnit", "UnrefUnit")
            and unit == "azazel-edge-core.service"
        )
        error, reply = _BusError(), ctypes.c_void_p()
        try:
            result = self.lib.sd_bus_call_method(
                self.bus,
                b"org.freedesktop.systemd1",
                b"/org/freedesktop/systemd1",
                b"org.freedesktop.systemd1.Manager",
                method.encode(),
                ctypes.byref(error),
                ctypes.byref(reply),
                b"s",
                ctypes.c_char_p(unit.encode()),
            )
            name = (
                error.name.decode("utf-8", errors="replace")[:4096]
                if error.name
                else None
            )
            message = (
                error.message.decode("utf-8", errors="replace")[:4096]
                if error.message
                else None
            )
            self.checked(method, result, name, message)
        finally:
            if reply:
                self.lib.sd_bus_message_unref(reply)
            self.lib.sd_bus_error_free(ctypes.byref(error))

    def close(self):
        if not self.bus:
            return
        failure = None
        try:
            self.checked("flush_bus", self.lib.sd_bus_flush(self.bus))
        except BaseException as error:
            failure = error
        finally:
            self.lib.sd_bus_close(self.bus)
            self.lib.sd_bus_unref(self.bus)
            self.bus = ctypes.c_void_p()
        if failure is not None:
            raise failure


def materialize(recipe, template):
    chunks = []
    for row in recipe:
        if row["kind"] == "raw_utf8":
            chunks.append(row["value"].encode())
        elif row["kind"] == "json":
            chunks.append(accounting.canonical(row["value"]))
        elif row["kind"] == "alert":
            event = copy.deepcopy(template)
            event["alert"]["signature_id"] = row["sid"]
            if row.get("padding_x_bytes"):
                event["padding"] = "x" * row["padding_x_bytes"]
            chunks.append(accounting.canonical(event))
        elif row["kind"] == "flow_padding":
            line = (
                b'{"event_type":"flow","padding":"'
                + b"x" * row["padding_x_bytes"]
                + b'"}\n'
            )
            if "line_bytes" in row:
                assert len(line) == row["line_bytes"]
            chunks.append(line * row["repeat"])
        else:
            raise AssertionError("unknown fixed recipe")
    raw = b"".join(chunks)
    assert len(raw) <= EVE_LIMIT
    return raw


def snapshot_fd(fd, limit):
    before = accounting.source_metadata(os.fstat(fd), detailed=True)
    assert before["size"] <= limit
    flags = fcntl.fcntl(fd, fcntl.F_GETFL)
    assert flags & os.O_ACCMODE == os.O_RDONLY
    raw = bytearray()
    while len(raw) <= limit:
        part = os.pread(fd, min(65536, limit + 1 - len(raw)), len(raw))
        if not part:
            break
        raw.extend(part)
    after = accounting.source_metadata(os.fstat(fd), detailed=True)
    assert before == after and len(raw) == before["size"] <= limit
    raw = bytes(raw)
    return raw, dict(
        before=before,
        after=after,
        sha256=accounting.sha256(raw),
        size=len(raw),
        fd=fd,
        flags=flags,
    )


class FiniteIngressLab(CloseReceiptLab):
    def __init__(self, g, role_command, variant):
        assert variant in ("main", "fault")
        self.g, self.role_command, self.variant = g, role_command, variant
        self.protocol_raw = Path(__file__).with_name(PROTOCOL_NAME).read_bytes()
        assert accounting.sha256(self.protocol_raw) == PROTOCOL_SHA256
        self.protocol = json.loads(self.protocol_raw)
        self.protocol_sha256 = PROTOCOL_SHA256
        self.allowed_case_ids = CASE_IDS
        self.public_directory = "finite-ingress-source-public"
        self.custody_schema = "outcome-live-close-custody/v2"
        self.cases = {}
        for case in self.protocol["cases"]:
            action = (
                "native_sigkill"
                if case["case_id"] == "ingress-native-killed"
                else (
                    "receiver_sigkill_then_normal_stop"
                    if case["case_id"] == "ingress-receiver-killed"
                    else "normal_stop"
                )
            )
            self.cases[case["case_id"]] = dict(
                case, action=action, custody_mode="live_parent_and_children"
            )
        assert set(self.cases) == CASE_IDS
        self.contexts = {}
        self._case_manager_clients = {}

    def _reset_case_counter(self, case_id, previous_session, expected_tip):
        client, referenced, failure = None, False, None
        held = False
        cleanup_errors = []
        if not hasattr(self, "_case_manager_clients"):
            self._case_manager_clients = {}
        assert case_id not in self._case_manager_clients
        try:
            client = SystemdUnitClient()
            client.open()
            client.call("RefUnit", self.g.UNIT)
            referenced = True
            actual_tip, _ = self.verify_case_start(
                case_id, previous_session=previous_session
            )
            assert actual_tip == expected_tip, (
                "Source changed while acquiring manager reference"
            )
            client.call("ResetFailedUnit", self.g.UNIT)
            self._case_manager_clients[case_id] = client
            held = True  # Pending ownership exists even before case context.
        except BaseException as error:
            failure = error
        finally:
            if client is not None and not held:
                if referenced:
                    try:
                        client.call("UnrefUnit", self.g.UNIT)
                    except BaseException as error:
                        cleanup_errors.append(
                            dict(type=type(error).__name__, message=str(error)[:4096])
                        )
                        failure = failure or error
                try:
                    client.close()
                except BaseException as error:
                    cleanup_errors.append(
                        dict(type=type(error).__name__, message=str(error)[:4096])
                    )
                    failure = failure or error
            self.g.record(
                "finite-ingress-manager-counter-transaction",
                case_id=case_id,
                unit=self.g.UNIT,
                timeout_usec=CALL_TIMEOUT_USEC,
                methods=client.trace if client is not None else [],
                reference_held=held,
                error=dict(type=type(failure).__name__, message=str(failure)[:4096])
                if failure
                else None,
                cleanup_errors=cleanup_errors,
            )
        if failure is not None:
            raise failure

    def release_case_reference(self, case_id, *, original=None):
        clients = getattr(self, "_case_manager_clients", {})
        client = clients.get(case_id)
        if client is None:
            return
        if original is None:
            context = self.contexts.get(case_id)
            assert (
                context is not None
                and context["exported"]
                and context["analysis_accepted"]
            ), "case originals must be archived before releasing manager reference"
        clients.pop(case_id)
        failure, cleanup_errors = None, []
        try:
            client.call("UnrefUnit", self.g.UNIT)
        except BaseException as error:
            failure = error
            cleanup_errors.append(
                dict(type=type(error).__name__, message=str(error)[:4096])
            )
        finally:
            try:
                client.close()
            except BaseException as error:
                failure = failure or error
                cleanup_errors.append(
                    dict(type=type(error).__name__, message=str(error)[:4096])
                )
        if failure is not None:
            context = self.contexts.get(case_id)
            hook = getattr(self, "post_snapshot_error", None)
            if hook is not None and context is not None and context["exported"]:
                hook(
                    case_id,
                    failure,
                    stage="manager-reference",
                    cleanup_errors=cleanup_errors,
                )
            if hook is None and (
                context is not None
                and context["exported"]
                and "failure.json" not in context["files"]
            ):
                raw = accounting.canonical(
                    dict(type=type(failure).__name__, message=str(failure)[:4096])
                )
                try:
                    self.g.write(
                        self.g.BASE / self.public_directory / case_id / "failure.json",
                        raw,
                    )
                    context["files"]["failure.json"] = raw
                except BaseException as error:
                    cleanup_errors.append(
                        dict(type=type(error).__name__, message=str(error)[:4096])
                    )
        try:
            self.g.record(
                "finite-ingress-manager-reference-released",
                case_id=case_id,
                unit=self.g.UNIT,
                methods=client.trace,
                cleanup_errors=cleanup_errors,
                primary_error_preserved=original is not None,
            )
        except BaseException as error:
            failure = failure or error
            cleanup_errors.append(
                dict(type=type(error).__name__, message=str(error)[:4096])
            )
            # Existing stderr is diagnostic only; do not overwrite the archived
            # failure slot or lose the first API error when publication fails.
            diagnostic = dict(
                case_id=case_id, methods=client.trace, cleanup_errors=cleanup_errors
            )
            if not hasattr(self, "_manager_cleanup_diagnostics"):
                self._manager_cleanup_diagnostics = {}
            self._manager_cleanup_diagnostics[case_id] = diagnostic
            try:
                sys.stderr.write(accounting.canonical(diagnostic).decode())
                sys.stderr.flush()
            except BaseException as stderr_error:
                cleanup_errors.append(
                    dict(
                        type=type(stderr_error).__name__,
                        message=str(stderr_error)[:4096],
                    )
                )
        if failure is not None and original is None:
            failure.manager_cleanup_errors = cleanup_errors
            failure.manager_method_trace = client.trace
            raise failure

    def eve_path(self):
        return Path(self.g.ENV["AZAZEL_EVE_PATH"])

    def error(self, context, stage, error):
        context["ingress"]["errors"].append(
            dict(stage=stage, type=type(error).__name__, message=str(error)[:4096])
        )

    def snapshot(self, context, name, *, held=True):
        try:
            fd = (
                context["eve_fd"]
                if held
                else os.open(
                    self.eve_path()
                    if name == "eve-path-final.raw"
                    else self.g.BASE / "native/log.jsonl",
                    os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC,
                )
            )
            try:
                raw, meta = snapshot_fd(
                    fd, EVE_LIMIT if name.startswith("eve-") else OBJECT_LIMIT
                )
                if not held:
                    assert meta["after"] == accounting.source_metadata(
                        (
                            self.eve_path()
                            if name.startswith("eve-")
                            else self.g.BASE / "native/log.jsonl"
                        ).lstat(),
                        detailed=True,
                    )
            finally:
                if not held:
                    os.close(fd)
            context["files"][name] = raw
            context["ingress"]["snapshots"][name] = meta
            assert (
                sum(
                    len(body)
                    for key, body in context["files"].items()
                    if key.startswith("eve-") and body is not None
                )
                <= EVE_TOTAL
            )
            return raw
        except (OSError, AssertionError) as exc:
            self.error(context, name, exc)
            raise

    def reset_input(self):
        g = self.g
        assert not g.Systemd().cores() and g.Systemd().snapshot()["ActiveState"] in (
            "inactive",
            "failed",
        )
        assert g.source_closed(), "never reset input against unclosed Source history"
        assert all(
            context["exported"]
            and context["analysis_accepted"]
            and context["eve_fd"] is None
            for context in self.contexts.values()
        )
        fd = os.open(self.eve_path(), os.O_WRONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        try:
            os.ftruncate(fd, 0)  # Synthetic input only, after immutable originals.
            os.fsync(fd)
        finally:
            os.close(fd)

    def begin(self, case_id, *, previous_session=None):
        self.reset_input()
        fd = os.open(self.eve_path(), os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
        opened_ns = time.monotonic_ns()
        initial = accounting.source_metadata(os.fstat(fd), detailed=True)
        assert initial["size"] == 0
        try:
            super().begin(case_id, previous_session=previous_session)
        except BaseException:
            os.close(fd)
            raise
        context = self.contexts[case_id]
        context["eve_fd"] = fd
        context["ingress"] = dict(
            schema_version="edge-finite-ingress-controller/v1",
            case_id=case_id,
            protocol_sha256=PROTOCOL_SHA256,
            session_ref=None,
            range_ref=None,
            started_ns=opened_ns,
            finished_ns=None,
            held_fd=dict(fd=fd, object=initial, opened_ns=opened_ns, closed_ns=None),
            snapshots=dict.fromkeys(RAW_NAMES),
            writer=[],
            mutation=None,
            markers=[],
            errors=[],
        )
        self.snapshot(context, "eve-start.raw")
        if self.variant == "fault":
            try:
                self.snapshot(context, "normalized-log-before.raw", held=False)
            except FileNotFoundError:
                pass  # Actual observed absence retained, never an empty file.

    def started(self, case_id, native_pid, session_ref):
        super().started(case_id, native_pid, session_ref)
        self.contexts[case_id]["ingress"]["session_ref"] = session_ref

    def signal_owned(self, context, signum, stopped):
        actor = context["controller"]["actors"]["native"]
        observed = accounting.actor(actor["pid"])
        assert observed["start_ticks"] == actor["start_ticks"]
        record = dict(
            pid=actor["pid"],
            start_ticks=actor["start_ticks"],
            signal=signum,
            requested_ns=time.monotonic_ns(),
            observed_ns=None,
            observed_state=None,
            error=None,
        )
        os.kill(actor["pid"], signum)

        def state():
            current = accounting.actor(actor["pid"])
            assert current["start_ticks"] == actor["start_ticks"]
            fields = Path(f"/proc/{actor['pid']}/status").read_text()
            value = fields.split("State:", 1)[1].split()[0]
            if (value in ("T", "t")) == stopped:
                record["observed_state"] = value
                return True
            return False

        self.g.wait_for(state)
        record["observed_ns"] = time.monotonic_ns()
        return record

    def append(self, context, raw, stage, *, pause=None):
        receipt = dict(
            stage=stage,
            pid=os.getpid(),
            tid=None,
            fd=None,
            flags=None,
            before=None,
            after=None,
            started_ns=None,
            finished_ns=None,
            offset_before=None,
            offset_after=None,
            requested_bytes=len(raw),
            written_bytes=0,
            write_calls=0,
            fsync_completed=False,
            joined=False,
            joined_ns=None,
            pause=pause,
            resume=None,
            error=None,
        )
        context["ingress"]["writer"].append(receipt)

        def write():
            receipt["tid"] = threading.get_native_id()
            receipt["started_ns"] = time.monotonic_ns()
            fd = None
            try:
                fd = os.open(
                    self.eve_path(),
                    os.O_WRONLY | os.O_APPEND | os.O_NOFOLLOW | os.O_CLOEXEC,
                )
                receipt["fd"] = fd
                receipt["flags"] = fcntl.fcntl(fd, fcntl.F_GETFL)
                receipt["before"] = accounting.source_metadata(
                    os.fstat(fd), detailed=True
                )
                assert all(
                    receipt["before"][k] == context["ingress"]["held_fd"]["object"][k]
                    for k in ("device", "inode", "owner_uid", "mode", "nlink")
                )
                receipt["offset_before"] = os.lseek(fd, 0, os.SEEK_END)
                while receipt["written_bytes"] < len(raw):
                    assert receipt["write_calls"] < 256
                    amount = os.write(fd, raw[receipt["written_bytes"] :])
                    receipt["write_calls"] += 1
                    assert amount > 0
                    receipt["written_bytes"] += amount
                os.fsync(fd)
                receipt["fsync_completed"] = True
                receipt["offset_after"] = os.lseek(fd, 0, os.SEEK_CUR)
                receipt["after"] = accounting.source_metadata(
                    os.fstat(fd), detailed=True
                )
            except BaseException as exc:
                receipt["error"] = dict(type=type(exc).__name__, message=str(exc))
            finally:
                if fd is not None:
                    os.close(fd)
                receipt["finished_ns"] = time.monotonic_ns()

        thread = threading.Thread(target=write, daemon=True)
        thread.start()
        thread.join(10)
        receipt["joined"] = not thread.is_alive()
        receipt["joined_ns"] = time.monotonic_ns()
        assert receipt["joined"] and receipt["error"] is None, receipt
        actual = self.snapshot(context, "eve-after-writer.raw")
        assert actual[receipt["offset_before"] : receipt["offset_after"]] == raw
        return receipt

    def source_marker(self, context, declaration, end):
        from azazel_edge.outcome.input_auth import SourceVerifier

        g = self.g
        result = None

        def available():
            nonlocal result
            try:
                raw, _ = stable_read(g.BUNDLE / "input", OBJECT_LIMIT)
            except AssertionError:
                return False  # Active writer bracket changed; no prefix admitted.
            if not raw.endswith(b"\n"):
                return False  # Await complete original frame; never drop the tail.
            verifier = SourceVerifier(g.fixture().p)
            tip = verifier.verify(raw)
            rows = [json.loads(line) for line in raw.splitlines()]
            matches = [
                wire["event"]
                for wire in rows
                if wire["event"].get("capture_origin", {}).get("session_ref")
                == context["controller"]["session_ref"]
                and wire["event"].get("normalized", {}).get("sid") == declaration["sid"]
            ]
            if len(matches) < declaration["occurrence"]:
                return False
            event = matches[declaration["occurrence"] - 1]
            origin = event.get("ingress_origin")
            assert (
                type(origin) is dict
                and origin["range_ref"] == context["controller"]["session_ref"]
            )
            if origin["end_offset"] != end:
                return False
            result = dict(
                kind="source",
                sid=declaration["sid"],
                occurrence=declaration["occurrence"],
                observed_ns=time.monotonic_ns(),
                session_ref=context["controller"]["session_ref"],
                range_ref=origin["range_ref"],
                source_checkpoint=tip,
                ingress_origin=origin,
                normalized_log_checkpoint=None,
            )
            return True

        g.wait_for(available)
        context["ingress"]["range_ref"] = result["range_ref"]
        context["ingress"]["markers"].append(result)

    def mutate(self, context, declaration):
        kind = declaration["kind"]
        pause = self.signal_owned(context, signal.SIGSTOP, True)
        self.snapshot(context, "eve-before-mutation.raw")
        record = dict(
            kind=kind,
            pid=os.getpid(),
            tid=threading.get_native_id(),
            started_ns=time.monotonic_ns(),
            finished_ns=None,
            path_before=accounting.source_metadata(
                self.eve_path().lstat(), detailed=True
            ),
            path_after=None,
            held_before=accounting.source_metadata(
                os.fstat(context["eve_fd"]), detailed=True
            ),
            held_after=None,
            renamed_relative_name=None,
            operation_completed=False,
            fsync_completed=False,
            pause=pause,
            resume=None,
            error=None,
        )
        context["ingress"]["mutation"] = record
        raw = materialize(
            declaration["replacement_recipe"], self.protocol["alert_template"]
        )
        fd = None
        try:
            if kind == "rename_replace":
                record["renamed_relative_name"] = "eve-finite-held.json"
                destination = self.g.BASE / record["renamed_relative_name"]
                assert not destination.exists()
                os.rename(self.eve_path(), destination)
                fd = os.open(
                    self.eve_path(),
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC,
                    0o644,
                )
                assert os.write(fd, raw) == len(raw)
            else:
                fd = os.open(
                    self.eve_path(), os.O_WRONLY | os.O_NOFOLLOW | os.O_CLOEXEC
                )
                if kind == "same_inode_truncate_shorter":
                    assert len(raw) < record["path_before"]["size"]
                    os.ftruncate(fd, 0)
                    assert os.write(fd, raw) == len(raw)
                else:
                    assert (
                        kind == "same_inode_same_length_overwrite"
                        and len(raw) == record["path_before"]["size"]
                    )
                    assert os.pwrite(fd, raw, 0) == len(raw)
            record["operation_completed"] = True
            os.fsync(fd)
            record["fsync_completed"] = True
            record["path_after"] = accounting.source_metadata(
                self.eve_path().lstat(), detailed=True
            )
            record["held_after"] = accounting.source_metadata(
                os.fstat(context["eve_fd"]), detailed=True
            )
        except BaseException as exc:
            record["error"] = dict(type=type(exc).__name__, message=str(exc))
            raise
        finally:
            if fd is not None:
                os.close(fd)
            record["finished_ns"] = time.monotonic_ns()
            record["resume"] = self.signal_owned(context, signal.SIGCONT, False)
        return len(raw)

    def normalized_marker(self, context, sid):
        def available():
            try:
                raw, meta = stable_read(self.g.BASE / "native/log.jsonl", OBJECT_LIMIT)
            except FileNotFoundError:
                return False
            if not raw.endswith(b"\n"):
                return False
            rows = [json.loads(line) for line in raw.splitlines()]
            if not any(row.get("normalized", {}).get("sid") == sid for row in rows):
                return False
            context["ingress"]["markers"].append(
                dict(
                    kind="normalized_log",
                    sid=sid,
                    occurrence=1,
                    observed_ns=time.monotonic_ns(),
                    session_ref=context["controller"]["session_ref"],
                    range_ref=context["ingress"]["range_ref"],
                    source_checkpoint=None,
                    ingress_origin=None,
                    normalized_log_checkpoint=meta,
                )
            )
            return True

        try:
            self.g.wait_for(available)
        except (OSError, AssertionError, ValueError) as exc:
            self.error(
                context, "normalized-log-marker", exc
            )  # Native snapshot remains a separate actual leg.

    def prepare_pressure(self, context):
        pause = self.signal_owned(context, signal.SIGSTOP, True)
        inventory = descriptor_inventory(context["controller"]["actors"]["native"])
        assert inventory["complete"]
        original = context["ingress"]["held_fd"]["object"]
        assert not any(
            entry["device"] == original["device"]
            and entry["inode"] == original["inode"]
            for entry in inventory["entries"]
        ), "pressure NOT_RUN: native already holds an EVE poll FD; no re-pause/retry"
        return pause

    def case(self, case_id):
        g, case = self.g, self.cases[case_id]
        self.begin(case_id)
        context = self.contexts[case_id]
        g.systemctl("start", g.UNIT)
        pid = g.live()
        self.started(case_id, pid, g.events()[-1]["capture_origin"]["session_ref"])
        accounting.await_input_start(g)
        pause = None
        if case_id == "ingress-backlog-shed":
            pause = self.prepare_pressure(context)
        raw = materialize(case["recipe"], self.protocol["alert_template"])
        assert accounting.sha256(raw) == case["recipe_intended_pin"]["sha256"]
        writer = self.append(context, raw, "initial", pause=pause)
        if pause is not None:
            writer["resume"] = self.signal_owned(context, signal.SIGCONT, False)
        actual = context["files"]["eve-after-writer.raw"]
        self.source_marker(context, case["signed_barrier"], actual.rfind(b"\n") + 1)
        if case.get("mutation"):
            end = self.mutate(context, case["mutation"])
            if case.get("post_mutation_signed_barrier"):
                self.source_marker(context, case["post_mutation_signed_barrier"], end)
        if case_id == "ingress-native-killed":
            os.kill(pid, signal.SIGKILL)
            g.wait_for(lambda: not g.Systemd().cores())
            g.wait_for(lambda: g.Systemd().snapshot()["ActiveState"] == "failed")
        elif case_id == "ingress-receiver-killed":
            receiver = context["controller"]["actors"]["receiver"]
            assert (
                accounting.actor(receiver["pid"])["start_ticks"]
                == receiver["start_ticks"]
            )
            os.kill(receiver["pid"], signal.SIGKILL)
            g.wait_for(lambda: not Path(f"/proc/{receiver['pid']}").exists())
            assert (
                accounting.actor(pid)["start_ticks"]
                == context["controller"]["actors"]["native"]["start_ticks"]
            )
            self.append(
                context,
                materialize(
                    case["second_append_recipe"], self.protocol["alert_template"]
                ),
                "post_receiver_failure",
            )
            self.normalized_marker(context, 90231902)
            g.systemctl("stop", g.UNIT)
            g.wait_for(lambda: not g.Systemd().cores())
        else:
            g.stop()
        self.stopped(case_id)
        if case_id not in ("ingress-native-killed", "ingress-receiver-killed"):
            g.observer()
        self.finalized(case_id)

    def export(self, case_id):
        context = self.contexts[case_id]
        assert not context["exported"]
        ingress = context.get("ingress")
        if ingress is not None:
            for name, held in (
                ("eve-held-final.raw", True),
                ("eve-path-final.raw", False),
            ):
                try:
                    self.snapshot(context, name, held=held)
                except (OSError, AssertionError):
                    pass
            if self.variant == "fault":
                try:
                    self.snapshot(context, "normalized-log-final.raw", held=False)
                except (OSError, AssertionError):
                    pass
            ingress["finished_ns"] = time.monotonic_ns()
            if context["eve_fd"] is not None:
                os.close(context["eve_fd"])
                context["eve_fd"] = None
                ingress["held_fd"]["closed_ns"] = time.monotonic_ns()
            context["files"]["ingress-controller.json"] = accounting.canonical(ingress)
        control, files = context["controller"], context["files"]
        control["finished_ns"] = time.monotonic_ns()
        files["close-controller.json"] = accounting.canonical(control)
        files["actor-fd-custody.json"] = accounting.canonical(control["fd_custody"])
        files["code-pins.json"] = accounting.canonical(
            dict(
                source_revision=control["source_revision"],
                protocol_sha256=PROTOCOL_SHA256,
                core_image_sha256=control["core_image_sha256"],
            )
        )
        if files.get("anchors-after.raw"):
            files["witness-boundary.json"] = accounting.canonical(
                accounting.witness_boundary(files["anchors-after.raw"])
            )
        directory = self.g.BASE / self.public_directory / case_id
        directory.mkdir(parents=True, exist_ok=False)
        assert set(files) <= FILES
        for name, body in files.items():
            if body is not None:
                self.g.write(directory / name, body)
        context["exported"] = True
        from azazel_edge.benchmark.finite_ingress import evaluate_finite_ingress

        artifacts = {name: files.get(name) for name in FILES}
        expected = {
            name: accounting.sha256(body) if body is not None else None
            for name, body in artifacts.items()
        }
        result = evaluate_finite_ingress(artifacts, expected=expected)
        self.g.write(directory / "evaluation.json", accounting.canonical(result))
        if control["outcome"] == "failure":
            return
        expected_status = (
            "bound_partial_evidence"
            if case_id
            in (
                "ingress-rename",
                "ingress-truncate",
                "ingress-same-inode-overwrite",
                "ingress-native-killed",
            )
            else (
                "bound_consumed_prefix"
                if case_id in ("ingress-partial-tail", "ingress-receiver-killed")
                else "bound_complete_input"
            )
        )
        assert result["status"] == expected_status, result
        if expected_status == "bound_complete_input":
            assert (
                result["whole_input_complete"] is True
                and result["committed_range_verified"] is True
                and result["unconfirmed_decision_outputs"] == 0
            )
        else:
            assert result["whole_input_complete"] is False
        if case_id == "ingress-native-killed":
            assert (
                result["ingress"] is None
                and result["unconfirmed_decision_outputs"] is None
            )
        elif case_id == "ingress-receiver-killed":
            assert type(result["ingress"]["counts"]["normalized_decisions"]) is int
            assert (
                result["unconfirmed_decision_outputs"]
                == result["ingress"]["counts"]["normalized_decisions"]
                - result["source_decisions"]
            )
        self.g.record(
            "finite-ingress-" + case_id,
            status=result["status"],
            whole_input_complete=result["whole_input_complete"],
        )
        context["analysis_accepted"] = True

    def exercise(self):
        g = self.g
        try:
            # One minimal existing handoff, no replay of old seven experiments.
            g.systemctl("start", g.UNIT)
            g.wait_for(lambda: len(g.Systemd().cores()) == 1)
            switch = g.Switch(g.BUNDLE)
            plan = switch.plan()
            assert switch.apply(plan, g.digest(plan))["status"] == "started"
            g.live()
            g.stop()
            g.observer()
            for case_id in self.protocol[
                "main_sequence" if self.variant == "main" else "fault_sequence"
            ]:
                self.case(case_id)
                self.release_case_reference(case_id)
        except BaseException as exc:
            self.teardown_failure(exc)
            raise

    def teardown_failure(self, original):
        # Lookup/manager failures cannot prevent original/error preservation.
        def note(stage, error):
            for context in self.contexts.values():
                if context.get("ingress") is not None and not context["exported"]:
                    self.error(context, stage, error)

        for context in self.contexts.values():
            try:
                native = context["controller"]["actors"].get("native")
                if (
                    native
                    and accounting.actor(native["pid"])["start_ticks"]
                    == native["start_ticks"]
                ):
                    os.kill(native["pid"], signal.SIGCONT)
            except (OSError, ValueError, KeyError, TypeError) as error:
                note("teardown-resume", error)
        for operation in (
            ("disable", self.g.UNIT),
            ("stop", self.g.UNIT, self.g.WITNESS),
        ):
            try:
                self.g.systemctl(*operation, check=False)
            except Exception as error:
                note("teardown-manager", error)
        try:
            self.retain_failures(original)
        except BaseException as error:
            note("failure-preservation", error)
            self.g.record(
                "finite-ingress-failure-preservation-error",
                type=type(error).__name__,
                message=str(error)[:4096],
            )
        finally:
            for case_id in list(getattr(self, "_case_manager_clients", {})):
                try:
                    self.release_case_reference(case_id, original=original)
                except BaseException as error:
                    note("manager-reference-cleanup", error)
                    # Never replace the original experiment failure.
                    self.g.record(
                        "finite-ingress-reference-cleanup-error",
                        case_id=case_id,
                        type=type(error).__name__,
                        message=str(error)[:4096],
                    )
