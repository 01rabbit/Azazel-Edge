'use strict';
const assert = require('node:assert/strict');
const {build, rowsOf} = require('../azazel_edge_web/static/soc_overview.js');
const fresh = {state:{snapshot_epoch:1000},health:{stale_flags:{snapshot:false}}};
assert.equal(build(fresh,1000,1,'all',false).freshness,'current');
assert.equal(build(fresh,1031,1,'all',false).freshness,'stale');
assert.equal(build(fresh,990,1,'all',false).freshness,'unknown');
assert.equal(build(fresh,1000,1,'all',true).freshness,'offline');
assert.equal(build({},1000,1,'all',false).freshness,'unknown');
assert.equal(build({...fresh,health:{stale_flags:{snapshot:'false'}}},1000,1,'all',false).freshness,'unknown');
assert.equal(build({...fresh,health:{stale_flags:{snapshot:true}}},1000,1,'all',false).freshness,'stale');
assert.equal(build({},1000).queueNow,null);
assert.equal(build({evidence:{alert_queues:{now:{count:0,items:[]}},recent_alerts:[]}},1000).queueNow,0);
assert.equal(build({evidence:{recent_alerts:[]}},1000).recentCount,0);
assert.equal(rowsOf({}).known,false);
assert.equal(rowsOf({alert_queues:{now:{items:[]}}}).known,true);
const evidence = {alert_queues:{now:{count:20,items:[{src_ip:'192.0.2.1',risk_score:5,trace_id:'untrusted',sid:42},{src_ip:'192.0.2.2',risk_score:90,decision_trace_id:'bound'}]},watch:{items:[{src_ip:'192.0.2.3',risk_score:100}]}}};
const model = build({evidence,boothFocus:{decision:{action:'isolate'},audit:{trace_id:'latest'},safety:{dry_run:true}}},1000,1,'now');
assert.equal(model.rows.length,2);
assert.equal(model.allRows.length,3);
assert.equal(model.rows[0].source,'192.0.2.2');
assert.equal(model.rows[1].decisionTrace,'');
assert.equal(model.queueNow,20); // Count is not inferred from truncated items.
assert.equal(model.action,'ISOLATE');
assert.equal(model.trace,'latest');
assert.equal(build({boothFocus:{decision:{action:'EXECUTE'}}},1000).action,'');
assert.equal(rowsOf({alert_queues:{now:{items:Array(200).fill({signature:'x'})}}}).rows.length,100);
const points = [{ts:100,value:10,queue_depth:4,stale_snapshot:false},{ts:999,queue_depth:7,stale_snapshot:true},{ts:1000,queue_depth:0,stale_snapshot:false},{ts:1001,queue_depth:'9',stale_snapshot:false},{ts:1006,queue_depth:4,stale_snapshot:false}];
const history = build({trends:{points}},1000,1,'all').points;
assert.deepEqual(history.map(p=>p.value),[4,null,0,null]);
assert.equal(build({trends:{points:[{ts:1,queue_depth:4,stale_snapshot:false}]}},4000,1).points.length,0);
assert.equal(build({trends:{points:[{ts:1,queue_depth:4,stale_snapshot:false}]}},4000,6).points.length,1);
assert.equal(build({trends:{points:'broken'}},1000).points.length,0);
console.log('SOC overview freshness, bounds, missing data, references and history checks passed');
